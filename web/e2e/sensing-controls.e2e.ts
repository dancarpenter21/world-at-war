import { expect, test, type BrowserContext } from "@playwright/test";
import { backendUrl, startBackend, type Backend } from "./support/server";
let backend: Backend, extra: BrowserContext[];
test.beforeEach(async () => { extra = []; backend = await startBackend(); });
test.afterEach(async ({}, info) => { if (info.status !== info.expectedStatus) await info.attach("backend.log", { body: backend.output(), contentType: "text/plain" }); await Promise.all(extra.map(context => context.close())); await backend.stop(); });

test("host speed widget stays synchronized, pause freezes time, and controller weather commits at a tick boundary", async ({ page, browser }) => {
  test.setTimeout(120000);
  await page.context().route("https://tile.openstreetmap.org/**", route => route.abort());
  await page.goto("/"); await page.getByRole("button", { name: /^Terrain and SIGINT Exercise/ }).click();
  await page.getByLabel("Game title").fill("Sensing controls regression"); await page.getByRole("button", { name: "Create game", exact: true }).click();
  await expect(page.getByRole("button", { name: /^Game Controller/ })).toBeVisible();
  const [game] = await (await page.request.get(backendUrl + "/v1/games")).json();
  const identity = await (await page.request.get(backendUrl + "/v1/auth/session")).json();
  const headers = { "x-csrf-token": identity.csrf_token, origin: new URL(page.url()).origin };
  const prefix = `${backendUrl}/v1/games/${game.id}`;
  const seats = await (await page.request.get(prefix + "/roles")).json();
  const controller = seats.find((seat: { observer_kind?: string }) => seat.observer_kind === "controller");
  expect((await page.request.put(`${prefix}/roles/${controller.id}/observer-grant`, { headers, data: { target_player_id: identity.player_id } })).ok()).toBe(true);
  expect((await page.request.post(prefix + "/pause", { headers, data: {} })).ok()).toBe(true);
  await page.getByRole("button", { name: /^Game Controller/ }).click();
  await expect(page.locator(".truth-map canvas")).toBeVisible({ timeout: 30000 });
  await page.getByLabel("Simulation speed").selectOption("60");
  await expect.poll(async () => (await (await page.request.get(backendUrl + "/v1/games")).json())[0].time_scale).toBe(60);
  const context = await browser.newContext({ baseURL: page.url() }); extra.push(context);
  const guest = await context.newPage(); await guest.goto("/"); await guest.getByRole("button", { name: "Join game", exact: true }).click(); await guest.getByRole("button", { name: /Sensing controls regression/ }).click();
  await guest.getByRole("button", { name: /^Pilot, CAP Alpha 2/ }).click();
  await expect(guest.getByLabel("Simulation speed")).toHaveText("60×");
  await expect(guest.getByLabel("Simulation speed")).not.toHaveJSProperty("tagName", "SELECT");
  await page.getByLabel("Simulation speed").selectOption("5");
  await expect(guest.getByLabel("Simulation speed")).toHaveText("5×");
  await page.getByLabel("Visibility (m)").fill("1200"); await page.getByRole("button", { name: "Apply weather", exact: true }).click();
  await expect(page.getByText(/Weather revision 1 committed/)).toBeVisible();
  const selection = await page.evaluate(() => JSON.parse(localStorage.getItem("world-at-war-session")!));
  const url = `${prefix}/environment?role_id=${selection.role_id}&lease_generation=${selection.lease_generation}`;
  const pending = await (await page.request.get(url)).json(); expect(pending.baseline.visibility_m).toBe(100000); expect(pending.pending.baseline.visibility_m).toBe(1200);
  await page.getByRole("button", { name: "Resume scenario" }).click();
  await expect.poll(async () => (await (await page.request.get(url)).json()).baseline.visibility_m).toBe(1200);
  await expect.poll(async () => (await (await page.request.get(backendUrl + "/v1/games")).json())[0].tick).toBeGreaterThan(3);
  await expect(guest.getByRole("button", { name: "Radar off", exact: true })).toBeEnabled({ timeout: 15_000 });
  await guest.getByRole("button", { name: "Radar off", exact: true }).click();
  await expect(guest.getByText(/Radar order: executed/)).toBeVisible();
  await expect(guest.getByText(/Last confirmed state: Off/)).toBeVisible();
  await page.getByRole("button", { name: "Pause scenario" }).click();
  await expect(page.getByRole("button", { name: "Resume scenario" })).toBeVisible();
  const paused = (await (await page.request.get(backendUrl + "/v1/games")).json())[0].tick;
  await page.waitForTimeout(700);
  await expect(async () => { const current = (await (await page.request.get(backendUrl + "/v1/games")).json())[0]; expect(current.tick).toBe(paused); }).toPass({ intervals: [500, 1000], timeout: 2000 });
  await page.screenshot({ path: "test-results/sensing-clock-weather.png", fullPage: true });
});
