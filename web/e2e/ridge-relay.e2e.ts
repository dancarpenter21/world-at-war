import { expect, test } from "@playwright/test";
import { backendUrl, startBackend, type Backend } from "./support/server";
import { playerRequests } from "./support/players";
let backend: Backend;
test.beforeEach(async () => { backend = await startBackend(); });
test.afterEach(async ({}, info) => {
  if (info.status !== info.expectedStatus) await info.attach("backend.log", { body: backend.output(), contentType: "text/plain" });
  await backend.stop();
});
for (const phone of [false, true]) test(`ridge relay restores reports and a command on ${phone ? "phone" : "desktop"}`, async ({ page }, info) => {
  test.setTimeout(90000);
  if (phone) await page.setViewportSize({ width: 390, height: 844 });
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.route(/https:\/\/[^/]*tile\.openstreetmap\.org\//, route => route.abort());
  await page.goto("/");
  await page.getByRole("button", { name: /^Ridge Relay Exercise/ }).click();
  const creation = page.waitForResponse(r => r.url().endsWith("/v1/games") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Create game", exact: true }).click();
  const prefix = `${backendUrl}/v1/games/${(await (await creation).json()).game.id}`;
  const role = "00000000-0000-0000-0000-000000004e86";
  const claim = page.waitForResponse(r => r.url().endsWith(`/roles/${role}/claim`));
  await page.getByRole("button", { name: /^Exercise Commander/ }).click();
  const seat = await (await claim).json();
  const auth = `role_id=${role}&lease_generation=${seat.lease_generation}`;
  const identity = await (await page.request.get(`${backendUrl}/v1/auth/session`)).json();
  const headers = { origin: new URL(page.url()).origin, "x-csrf-token": identity.csrf_token };
  const pilot = playerRequests(page, "commander");
  try {
    expect((await pilot.post(`${prefix}/roles/00000000-0000-0000-0000-000000004e87/claim`, { data: { player_id: "pilot" } })).ok()).toBe(true);
    await page.getByRole("button", { name: "Start scenario", exact: true }).click();
    if (phone) await page.getByRole("button", { name: "Commands", exact: true }).click();
    const movement = page.getByRole("region", { name: "Movement orders" });
    await movement.getByLabel("Command unit").selectOption("00000000-0000-0000-0000-00000000000b");
    await movement.getByLabel("Speed (m/s)").fill("10");
    const submitted = page.waitForResponse(r => r.url().endsWith(`/roles/${role}/intent`) && r.request().method() === "POST");
    await movement.getByRole("button", { name: "Send movement order", exact: true }).click();
    const response = await submitted; expect(response.ok(), await response.text()).toBe(true);
    const intent = response.request().postDataJSON().intent;
    const receiptUrl = `${prefix}/roles/${role}/intents/${intent.intent_id}?lease_generation=${seat.lease_generation}`;
    const state = async () => (await (await page.request.get(`${prefix}/state?${auth}`)).json());
    await expect.poll(async () => (await state()).tick, { intervals: [100] }).toBeGreaterThanOrEqual(2);
    expect((await page.request.post(prefix + "/pause", { headers, data: {} })).ok()).toBe(true);
    const blocked = await state(); expect(blocked.tracks).toHaveLength(0);
    const local = await (await pilot.get(`${prefix}/state?player_id=pilot&role_id=00000000-0000-0000-0000-000000004e87`)).json();
    expect(local.tracks.length).toBeGreaterThan(0);
    const link = (picture: typeof blocked, to: string) => picture.communication_links.find((l: { from_entity_id: string; to_entity_id: string }) => l.from_entity_id.endsWith("000000000005") && l.to_entity_id.endsWith(to));
    expect(link(blocked,"00000000000b")).toMatchObject({ available: false, jammed: 0, geometry_status: "terrain_blocked" });
    expect((await (await page.request.get(receiptUrl)).json()).executed_tick).toBeUndefined();
    await page.getByRole("button", { name: "Network", exact: true }).click();
    await expect(page.getByRole("region", { name: "C2 network workspace" })).toBeVisible();
    await page.getByRole("button", { name: "Inspect Ridge headquarters", exact: true }).click();
    await page.getByRole("button", { name: /Ridge headquarters → Ridge sensor aircraft Terrain blocked/ }).click();
    await expect(page.getByRole("region", { name: "Link details" })).toContainText("Terrain blocked");
    await page.getByRole("button", { name: "Fit view", exact: true }).click();
    await page.waitForTimeout(300);
    await page.screenshot({ path: info.outputPath(`ridge-blocked-${phone ? "phone" : "desktop"}.png`), fullPage: true });
    expect((await page.request.post(prefix + "/start", { headers, data: {} })).ok()).toBe(true);
    await expect.poll(async () => (await (await page.request.get(receiptUrl)).json()).state, { timeout: 35000 }).toBe("executed");
    await expect.poll(async () => (await state()).tracks.length, { timeout: 15000 }).toBeGreaterThan(0);
    const after = await state(); expect(link(after,"00000000000c")).toMatchObject({ available: true, geometry_status: "clear" });
    expect(after.tracks.every((t: { received_tick: number; observed_tick: number }) => t.received_tick > t.observed_tick)).toBe(true);
    expect((await page.request.post(prefix + "/pause", { headers, data: {} })).ok()).toBe(true);
    await page.getByRole("button", { name: "Clear selection · show all messages", exact: true }).click();
    await page.getByRole("tab", { name: "Topology", exact: true }).click();
    await page.getByRole("button", { name: "All connections", exact: true }).click();
    await page.getByRole("button", { name: "Inspect Ridge headquarters", exact: true }).click();
    await page.getByRole("button", { name: /Ridge headquarters → Relay aircraft/ }).click();
    await expect(page.getByRole("region", { name: "Link details" })).toContainText("Clear line of sight");
    await page.getByRole("button", { name: "Fit view", exact: true }).click();
    await page.waitForTimeout(300);
    await page.screenshot({ path: info.outputPath(`ridge-restored-${phone ? "phone" : "desktop"}.png`), fullPage: true });
    await page.reload();
    await expect(page.getByRole("button", { name: "Resume scenario", exact: true })).toBeVisible();
    expect((await (await page.request.get(receiptUrl)).json()).state).toBe("executed");
    expect(errors).toEqual([]);
  } finally { await pilot.dispose(); }
});
