import { expect, test } from "@playwright/test";
import { backendUrl, startBackend, type Backend } from "./support/server";
import type { LogisticsProjection } from "../src/logisticsModel";
let backend: Backend;
test.beforeEach(async () => { backend = await startBackend(); });
test.afterEach(async ({}, info) => { if (info.status !== info.expectedStatus) await info.attach("backend.log", { body: backend.output(), contentType: "text/plain" }); await backend.stop(); });
for (const phone of [false, true]) test(`delivered aerial refueling and logistics reports on ${phone ? "phone" : "desktop"}`, async ({ page }, info) => {
  test.setTimeout(90000);
  if (phone) await page.setViewportSize({ width: 390, height: 844 });
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.route(/https:\/\/[^/]*tile\.openstreetmap\.org\//, route => route.abort());
  await page.goto("/");
  await page.getByRole("button", { name: /^Joint Sustainment Exercise/ }).click();
  const creation = page.waitForResponse(r => r.url().endsWith("/v1/games") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Create game", exact: true }).click();
  const prefix = `${backendUrl}/v1/games/${(await (await creation).json()).game.id}`;
  const role = "00000000-0000-0000-0000-000000004e86";
  const claim = page.waitForResponse(r => r.url().endsWith(`/roles/${role}/claim`));
  await page.getByRole("button", { name: /^Exercise Commander/ }).click();
  const held = await (await claim).json();
  const state = async () => (await (await page.request.get(`${prefix}/state?role_id=${role}&lease_generation=${held.lease_generation}`)).json()) as { logistics: LogisticsProjection };
  expect((await state()).logistics.units).toHaveLength(0);
  await page.getByRole("button", { name: "Start scenario", exact: true }).click();
  if (phone) await page.getByRole("button", { name: "Commands", exact: true }).click();
  await expect.poll(async () => (await state()).logistics.units.length, { timeout: 30000 }).toBe(6);
  const workspace = page.locator(".logistics-workspace");
  await expect(workspace).toBeVisible();
  const submit = async (button: string) => {
    const sent = page.waitForResponse(r => r.url().endsWith(`/roles/${role}/intent`) && r.request().method() === "POST");
    await workspace.getByRole("button", { name: button, exact: true }).click();
    const response = await sent; expect(response.ok(), await response.text()).toBe(true);
    const intent = response.request().postDataJSON().intent;
    await expect.poll(async () => (await (await page.request.get(`${prefix}/roles/${role}/intents/${intent.intent_id}?lease_generation=${held.lease_generation}`)).json()).state, { timeout: 20000 }).toBe("executed");
    return intent;
  };
  await workspace.getByLabel("Logistics unit", { exact: true }).selectOption("00000000-0000-0000-0000-00000000000d");
  await workspace.getByLabel("Refueling interface", { exact: true }).selectOption("boom");
  await submit("Establish refueling support");
  await workspace.getByLabel("Logistics unit", { exact: true }).selectOption("00000000-0000-0000-0000-00000000000b");
  await workspace.getByLabel("Assigned donor", { exact: true }).selectOption("00000000-0000-0000-0000-00000000000d");
  await workspace.getByLabel("Fuel quantity (kg)", { exact: true }).fill("100");
  const receiver = () => state().then(s => s.logistics.units.find(u => u.unit_id.endsWith("00000000000b"))!);
  const before = (await receiver()).fuel_kg;
  const original = await submit("Request fuel transfer");
  await expect.poll(async () => (await receiver()).transferred_kg, { timeout: 25000 }).toBe(100);
  expect((await receiver()).fuel_kg).toBeGreaterThan(before);
  const session = await (await page.request.get(`${backendUrl}/v1/auth/session`)).json();
  const duplicate = await page.request.post(`${prefix}/roles/${role}/intent`, { headers: { origin: new URL(page.url()).origin, "x-csrf-token": session.csrf_token }, data: { lease_generation: held.lease_generation, intent: original } });
  expect(duplicate.ok(), await duplicate.text()).toBe(true);
  expect((await receiver()).transferred_kg).toBe(100);
  await page.getByRole("button", { name: "Pause scenario", exact: true }).click();
  await expect(workspace).toContainText("100.0 kg transferred");
  const completed=workspace.locator(":scope > .logistics-status").getByText(/100\.0 kg transferred/);
  await completed.scrollIntoViewIfNeeded();
  await expect(completed).toBeVisible();
  await page.screenshot({ path: info.outputPath(`logistics-refueling-${phone ? "phone" : "desktop"}.png`), fullPage: true });
  await page.reload();
  if (phone) await page.getByRole("button", { name: "Commands", exact: true }).click();
  await expect(page.locator(".logistics-workspace")).toContainText("100.0 kg transferred");
  expect(errors).toEqual([]);
});
