import { expect, test } from "@playwright/test";
import { backendUrl, startBackend, type Backend } from "./support/server";

const database = process.env.PERSISTENCE_E2E_DATABASE_URL;
test.describe("durable accounts and recovery", () => {
  test.skip(!database, "requires a dedicated PERSISTENCE_E2E_DATABASE_URL");
  let backend: Backend;
  test.beforeEach(async () => { backend = await startBackend({ DATABASE_URL: database! }); });
  test.afterEach(async ({}, info) => {
    if (backend && info.status !== info.expectedStatus) await info.attach("backend.log", { body: backend.output(), contentType: "text/plain" });
    await backend?.stop();
  });
  test("saved identity, game, role and tick survive a crash; sign-in and shared-tab logout work", async ({ page }) => {
    test.setTimeout(90_000);
    await page.route("https://tile.openstreetmap.org/**", route => route.abort());
    await page.goto("/");
    await expect(page.getByRole("button", { name: "Save guest as account" })).toBeVisible();
    const original = await (await page.context().request.get(backendUrl + "/v1/auth/session")).json();
    const username = `commander_${Date.now()}`;
    const password = "a long browser test password";
    await page.getByRole("button", { name: "Save guest as account" }).click();
    const dialog = page.getByRole("dialog", { name: "Save your account" });
    await dialog.getByLabel("Username").fill(username);
    await dialog.getByLabel("Password").fill(password);
    await dialog.getByRole("button", { name: "Create account", exact: true }).click();
    await expect(page.getByText(`Signed in as ${username}`, { exact: true })).toBeVisible();
    await page.getByRole("button", { name: /^Command Link Exercise/ }).click();
    await page.getByLabel("Game title").fill(`Recovered game ${username}`);
    await page.getByRole("button", { name: "Create game", exact: true }).click();
    await page.getByRole("button", { name: /^Exercise Commander/ }).click();
    await page.getByRole("button", { name: "Start scenario", exact: true }).click();
    await expect(page.locator(".globe canvas")).toBeVisible({ timeout: 20_000 });
    const selected = await page.evaluate(() => JSON.parse(localStorage.getItem("world-at-war-session")!));
    const stateUrl = `${backendUrl}/v1/games/${selected.game_id}/state?role_id=${selected.role_id}&lease_generation=${selected.lease_generation}`;
    await expect.poll(async () => (await (await page.context().request.get(stateUrl)).json()).tick).toBeGreaterThan(1);
    const before = await (await page.context().request.get(stateUrl)).json();
    await backend.restart("SIGKILL");
    const recovered = await (await page.context().request.get(stateUrl)).json();
    expect(recovered.tick).toBeGreaterThanOrEqual(before.tick);
    const games = await (await page.context().request.get(backendUrl + "/v1/games")).json();
    expect(games.find((game: { id: string }) => game.id === selected.game_id).status).toBe("paused");
    await page.reload();
    await expect(page.getByText("Scenario paused", { exact: true })).toBeVisible();
    expect((await (await page.context().request.get(backendUrl + "/v1/auth/session")).json()).player_id).toBe(original.player_id);
    await page.getByRole("button", { name: "Leave scenario", exact: true }).click();
    const tab = await page.context().newPage();
    await tab.goto(page.url());
    await expect(tab.getByRole("button", { name: "Sign out", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Sign out", exact: true }).click();
    await expect(tab.getByRole("button", { name: "Save guest as account", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    const login = page.getByRole("dialog", { name: "Sign in", exact: true });
    await login.getByLabel("Username").fill(username);
    await login.getByLabel("Password").fill("incorrect long password");
    await login.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(login.getByRole("alert")).toHaveText("Username or password is incorrect");
    await login.getByLabel("Password").fill(password);
    await login.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(page.getByText(`Signed in as ${username}`, { exact: true })).toBeVisible();
    await expect(tab.getByText(`Signed in as ${username}`, { exact: true })).toBeVisible();
    expect((await (await page.context().request.get(backendUrl + "/v1/auth/session")).json()).player_id).toBe(original.player_id);
    await page.screenshot({ path: test.info().outputPath("saved-account-recovered.png") });
    await tab.close();
  });
});
